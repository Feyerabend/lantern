#!/usr/bin/env python3
"""Embed a text file in a C header as a string constant.

usage: embed.py <in-file> <out.h> <c-name>
"""
import sys


def main():
    src, out, name = sys.argv[1], sys.argv[2], sys.argv[3]
    with open(src, encoding="utf-8") as f:
        text = f.read()
    with open(out, "w", encoding="ascii") as f:
        f.write(f"/* Generated by tools/embed.py from {src}. Do not edit. */\n")
        f.write(f"static const char {name}[] =\n")
        for line in text.splitlines(keepends=True):
            # UTF-8, with octal escapes for the bytes beyond ASCII (M15)
            esc = "".join(
                "\\\\" if b == 92 else '\\"' if b == 34 else "\\n" if b == 10
                else chr(b) if 32 <= b < 127 else "\\%03o" % b
                for b in line.encode("utf-8")
            )
            f.write(f'    "{esc}"\n')
        f.write(";\n")


if __name__ == "__main__":
    main()
